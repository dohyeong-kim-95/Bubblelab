// id는 "<별자리>:<바이어>" (예: "Ori:α"). 선 데이터가 이 id로 별을 가리킨다.
export const STARS = [];
const BY_ID = new Map();
for (const con of CONSTELLATIONS) {
  for (const [bayer, ra, dec, mag, name = null, color = null] of con.stars) {
    const star = { id: `${con.id}:${bayer}`, con: con.id, bayer, ra, dec, mag, name, color };
    STARS.push(star);
    BY_ID.set(star.id, star);
  }
}

export const starById = (id) => BY_ID.get(id) ?? null;

// "α-β,β-γ" → [[별,별], …]. "Peg:α" 처럼 다른 별자리를 가리키는 끝점도 받는다
// (페가수스 사각형의 한 꼭짓점은 안드로메다 소속이라 이런 경우가 실제로 있다).
export const SEGMENTS = [];
for (const con of CONSTELLATIONS) {
  for (const pair of con.lines.split(",").filter(Boolean)) {
    const ends = pair.split("-").map((token) =>
      BY_ID.get(token.includes(":") ? token : `${con.id}:${token}`));
    if (ends.length === 2 && ends[0] && ends[1]) SEGMENTS.push({ con: con.id, a: ends[0], b: ends[1] });
  }
}

export const constellationById = (id) => CONSTELLATIONS.find((c) => c.id === id) ?? null;

// ── 시각·좌표 변환 ────────────────────────────────────────────
export const julianDay = (date) => date.getTime() / 86400000 + 2440587.5;

// 그리니치 평균 항성시(도). 하늘이 하루에 한 바퀴 도는 각도를 준다.
export function gmst(date) {
  const d = julianDay(date) - 2451545.0;
  return ((280.46061837 + 360.98564736629 * d) % 360 + 360) % 360;
}

// 지방 항성시(도). 동경을 양수로 받는다.
export const lst = (date, lonDeg) => ((gmst(date) + lonDeg) % 360 + 360) % 360;

// 적도좌표(적경 시, 적위 도) → 지평좌표(고도 도, 방위 도: 북 0, 동 90)
export function equatorialToHorizontal(ra, dec, latDeg, lonDeg, date) {
  const H = (lst(date, lonDeg) - ra * 15) * D2R;
  const d = dec * D2R, lat = latDeg * D2R;
  const sinAlt = Math.sin(lat) * Math.sin(d) + Math.cos(lat) * Math.cos(d) * Math.cos(H);
  const alt = Math.asin(Math.max(-1, Math.min(1, sinAlt)));
  const az = Math.atan2(
    -Math.cos(d) * Math.sin(H),
    Math.cos(lat) * Math.sin(d) - Math.sin(lat) * Math.cos(d) * Math.cos(H));
  return { alt: alt * R2D, az: ((az * R2D) % 360 + 360) % 360 };
}

// 지평좌표 → 적도좌표. 화면이 겨눈 방향이 하늘의 어디인지 알아낼 때 쓴다.
export function horizontalToEquatorial(altDeg, azDeg, latDeg, lonDeg, date) {
  const alt = altDeg * D2R, az = azDeg * D2R, lat = latDeg * D2R;
  const sinDec = Math.sin(lat) * Math.sin(alt) + Math.cos(lat) * Math.cos(alt) * Math.cos(az);
  const dec = Math.asin(Math.max(-1, Math.min(1, sinDec)));
  const H = Math.atan2(
    -Math.cos(alt) * Math.sin(az),
    Math.cos(lat) * Math.sin(alt) - Math.sin(lat) * Math.cos(alt) * Math.cos(az));
  let ra = (lst(date, lonDeg) - H * R2D) / 15;
  ra = ((ra % 24) + 24) % 24;
  return { ra, dec: dec * R2D };
}

// 두 적도좌표 사이 각거리(도)
export function angularSeparation(ra1, dec1, ra2, dec2) {
  const d1 = dec1 * D2R, d2 = dec2 * D2R, dRa = (ra1 - ra2) * 15 * D2R;
  const cos = Math.sin(d1) * Math.sin(d2) + Math.cos(d1) * Math.cos(d2) * Math.cos(dRa);
  return Math.acos(Math.max(-1, Math.min(1, cos))) * R2D;
}

// ── 화면 투영 ─────────────────────────────────────────────────
// 시선 방향을 중심으로 한 입체투영(stereographic). 넓은 화각에서도 별자리
// 모양이 덜 일그러진다. 반환 x는 오른쪽, y는 위쪽이 양수(라디안 비례 단위).
const unit = (ra, dec) => {
  const r = ra * 15 * D2R, d = dec * D2R;
  return [Math.cos(d) * Math.cos(r), Math.cos(d) * Math.sin(r), Math.sin(d)];
};
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const cross = (a, b) => [
  a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const norm = (v) => {
  const len = Math.hypot(v[0], v[1], v[2]) || 1;
  return [v[0] / len, v[1] / len, v[2] / len];
};

// 중심 방향(적경·적위)과 "위쪽"으로 삼을 방향(기본: 천구 북극)으로 화면축을 만든다.
export function makeProjection(centerRa, centerDec, rollDeg = 0) {
  const forward = unit(centerRa, centerDec);
  const pole = [0, 0, 1];
  // 시선이 천구극과 겹치면 극을 위로 삼을 수 없다 — 다른 축으로 피한다.
  const seed = Math.abs(dot(forward, pole)) > 0.999 ? [1, 0, 0] : pole;
  let right = norm(cross(seed, forward));
  let up = cross(forward, right);
  if (rollDeg) {
    const r = rollDeg * D2R, c = Math.cos(r), s = Math.sin(r);
    const nr = right.map((v, i) => v * c + up[i] * s);
    const nu = right.map((v, i) => -v * s + up[i] * c);
    right = nr; up = nu;
  }
  return (ra, dec) => {
    const v = unit(ra, dec);
    const cosC = dot(v, forward);
    if (cosC <= -0.999) return null;            // 정확히 반대편 — 그릴 수 없다
    const k = 2 / (1 + cosC);
    return { x: k * dot(v, right), y: k * dot(v, up), cosC };
  };
}

// ── 시야 안의 별과 대표 별자리 ────────────────────────────────
export function starsInView(centerRa, centerDec, radiusDeg, maxMag = 4.6) {
  return STARS.filter((s) => s.mag <= maxMag
    && angularSeparation(centerRa, centerDec, s.ra, s.dec) <= radiusDeg);
}

// 시야에서 "이 방향의 별자리"를 하나 고른다. 밝을수록, 중심에 가까울수록 큰 점수.
// 아무 별도 없으면(빈 하늘) null — 화면은 그 경우를 따로 안내한다.
export function dominantConstellation(centerRa, centerDec, radiusDeg) {
  const score = new Map();
  for (const star of starsInView(centerRa, centerDec, radiusDeg)) {
    const sep = angularSeparation(centerRa, centerDec, star.ra, star.dec);
    const brightness = Math.max(0.2, 5.2 - star.mag);       // 어두운 별도 조금은 센다
    const nearness = 1 - 0.7 * (sep / radiusDeg);           // 중심에 가까울수록 가산
    score.set(star.con, (score.get(star.con) ?? 0) + brightness * nearness);
  }
  let best = null, bestScore = 0;
  for (const [con, value] of score) if (value > bestScore) { best = con; bestScore = value; }
  return best ? { ...constellationById(best), score: bestScore } : null;
}
